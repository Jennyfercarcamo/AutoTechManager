    private void tblRepuestosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblRepuestosMouseClicked
        // TODO add your handling code here:
         int fila = tblRepuestos.getSelectedRow();

    if (fila >= 0) {
        txtCodigo.setText(tblRepuestos.getValueAt(fila, 1).toString());
        txtNombre.setText(tblRepuestos.getValueAt(fila, 2).toString());
        cbmMarca.setSelectedItem(tblRepuestos.getValueAt(fila, 3).toString());
        cbmCategoria.setSelectedItem(tblRepuestos.getValueAt(fila, 4).toString());
        txtPrecioCompra.setText(tblRepuestos.getValueAt(fila, 5).toString());
        txtPrecioVenta.setText(tblRepuestos.getValueAt(fila, 6).toString());

        spStock.setValue(Integer.parseInt(
                tblRepuestos.getValueAt(fila, 7).toString()));

        chkActivo.setSelected(
                tblRepuestos.getValueAt(fila, 8).toString().equals("Activo"));
    }

    }//GEN-LAST:event_tblRepuestosMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
         int fila = tblRepuestos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un repuesto de la tabla.");
        return;
    }

    try {
        Repuestos repuesto = new Repuestos();

        repuesto.setIdRepuesto(Integer.parseInt(
                tblRepuestos.getValueAt(fila, 0).toString()));

        repuesto.setCodigo(txtCodigo.getText().trim());
        repuesto.setNombre(txtNombre.getText().trim());
        repuesto.setDescripcion("");
        repuesto.setIdProveedor(0);
        repuesto.setCosto(Double.parseDouble(txtPrecioCompra.getText().trim()));
        repuesto.setPrecioVenta(Double.parseDouble(txtPrecioVenta.getText().trim()));
        repuesto.setStock(Integer.parseInt(spStock.getValue().toString()));
        repuesto.setStockMinimo(5);
        repuesto.setEstado(chkActivo.isSelected());

        RepuestosDAO dao = new RepuestosDAO();

        if (dao.actualizar(repuesto)) {
            JOptionPane.showMessageDialog(this, "Repuesto actualizado correctamente.");
            cargarTabla();
            limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo actualizar el repuesto.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Revise los valores numéricos.");
    }

    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblRepuestos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un repuesto de la tabla.");
        return;
    }

    int id = Integer.parseInt(tblRepuestos.getValueAt(fila, 0).toString());

    int confirmar = JOptionPane.showConfirmDialog(
            this,
            "¿Desea desactivar este repuesto?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmar == JOptionPane.YES_OPTION) {
        RepuestosDAO dao = new RepuestosDAO();

        if (dao.desactivar(id)) {
            JOptionPane.showMessageDialog(this, "Repuesto desactivado correctamente.");
            cargarTabla();
            limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo desactivar el repuesto.");
        }
    }

        
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void txtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyReleased
        // TODO add your handling code here:
        
          String buscar = txtBuscar.getText().trim().toLowerCase();

    DefaultTableModel modelo = (DefaultTableModel) tblRepuestos.getModel();
    modelo.setRowCount(0);

    RepuestosDAO dao = new RepuestosDAO();

    for (Repuestos repuesto : dao.listar()) {
        if (repuesto.getCodigo().toLowerCase().contains(buscar)
                || repuesto.getNombre().toLowerCase().contains(buscar)) {

            modelo.addRow(new Object[]{
    repuesto.getIdRepuesto(),
    repuesto.getCodigo(),
    repuesto.getNombre(),
    repuesto.getMarca(),
    repuesto.getCategoria(),
    repuesto.getCosto(),
    repuesto.getPrecioVenta(),
    repuesto.getStock(),
    repuesto.isEstado() ? "Activo" : "Inactivo"
});
        }
    }

        
    }//GEN-LAST:event_txtBuscarKeyReleased

