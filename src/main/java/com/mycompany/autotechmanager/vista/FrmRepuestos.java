    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
    if (txtCodigo.getText().trim().isEmpty()
            || txtNombre.getText().trim().isEmpty()
            || txtPrecioCompra.getText().trim().isEmpty()
            || txtPrecioVenta.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Complete los campos obligatorios.");
        return;
    }

    try {
        Repuestos repuesto = new Repuestos();

        repuesto.setCodigo(txtCodigo.getText().trim());
        repuesto.setNombre(txtNombre.getText().trim());
        repuesto.setDescripcion("");
        repuesto.setIdProveedor(0);
        repuesto.setCosto(Double.parseDouble(
                txtPrecioCompra.getText().trim()));
        repuesto.setPrecioVenta(Double.parseDouble(
                txtPrecioVenta.getText().trim()));
        repuesto.setStock(Integer.parseInt(
                spStock.getValue().toString()));
        repuesto.setStockMinimo(5);
        repuesto.setEstado(chkActivo.isSelected());
        
        repuesto.setMarca(cbmMarca.getSelectedItem().toString());
        repuesto.setCategoria(cbmCategoria.getSelectedItem().toString());

        RepuestosDAO dao = new RepuestosDAO();

        if (dao.registrar(repuesto)) {
            JOptionPane.showMessageDialog(this,
                    "Repuesto registrado correctamente.");

            cargarTabla();
            limpiar();
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar el repuesto.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Revise los valores numéricos.");
    }

    }//GEN-LAST:event_btnGuardarActionPerformed

