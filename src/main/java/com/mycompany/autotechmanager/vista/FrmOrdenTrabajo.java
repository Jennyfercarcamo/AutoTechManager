    private void tblOrdenesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOrdenesMouseClicked
        // TODO add your handling code here:
        int fila = tblOrdenes.getSelectedRow();

if (fila >= 0) {

    txtCodigo.setText(tblOrdenes.getValueAt(fila, 0).toString());
    txtFecha.setText(tblOrdenes.getValueAt(fila, 1).toString());

    cbmCliente.setSelectedItem(tblOrdenes.getValueAt(fila, 2));
    cbmVehiculo.setSelectedItem(tblOrdenes.getValueAt(fila, 3));
    cbmMecanico.setSelectedItem(tblOrdenes.getValueAt(fila, 4));

    cbmEstado.setSelectedItem(tblOrdenes.getValueAt(fila, 5));

    txtSintomas.setText(tblOrdenes.getValueAt(fila, 6).toString());
}
        
    }//GEN-LAST:event_tblOrdenesMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
         try {
        int idOrden = Integer.parseInt(txtCodigo.getText());

        OrdenTrabajo orden = new OrdenTrabajo();

        orden.setIdOrden(idOrden);
       String clienteSeleccionado = cbmCliente.getSelectedItem().toString();
       int idCliente = Integer.parseInt(clienteSeleccionado.split(" - ")[0]);

        orden.setIdCliente(idCliente);


        String vehiculoSeleccionado = cbmVehiculo.getSelectedItem().toString();
        int idVehiculo = Integer.parseInt(vehiculoSeleccionado.split(" - ")[0]);

          orden.setIdVehiculo(idVehiculo);
          
         
          
          if (txtKilometraje.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingrese el kilometraje.");
    return;
}

        orden.setKilometraje(Integer.parseInt(txtKilometraje.getText()));
        orden.setSintomas(txtSintomas.getText());
        orden.setDiagnosticoPreliminar(txtDiagnostico.getText());
        orden.setEstado(cbmEstado.getSelectedItem().toString());

        orden.setFechaIngreso(
            Timestamp.valueOf(txtFecha.getText())
        );
        
         String mecanicoSeleccionado = cbmMecanico.getSelectedItem().toString();
           int idMecanico = Integer.parseInt(mecanicoSeleccionado.split(" - ")[0]);

          orden.setResponsable(idMecanico);

       

        OrdenTrabajoDAO dao = new OrdenTrabajoDAO();

        if (dao.actualizar(orden)) {
            JOptionPane.showMessageDialog(this,
                    "Orden actualizada correctamente.");
            cargarOrdenes();
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo actualizar la orden.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error al actualizar: " + e.getMessage());
    }

    }//GEN-LAST:event_btnEditarActionPerformed

