    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
           try {

        if (cbmCliente.getSelectedItem() == null
                || cbmVehiculo.getSelectedItem() == null
                || cbmMecanico.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(this,
                    "Seleccione cliente, vehículo y mecánico.");
            return;
        }

        String cliente = cbmCliente.getSelectedItem().toString();
        String vehiculo = cbmVehiculo.getSelectedItem().toString();
        String mecanico = cbmMecanico.getSelectedItem().toString();

        int idCliente = Integer.parseInt(cliente.split(" - ")[0]);
        int idVehiculo = Integer.parseInt(vehiculo.split(" - ")[0]);
        int idMecanico = Integer.parseInt(mecanico.split(" - ")[0]);

        int kilometraje = Integer.parseInt(txtKilometraje.getText());

        OrdenTrabajo orden = new OrdenTrabajo();

        orden.setIdCliente(idCliente);
        orden.setIdVehiculo(idVehiculo);
        orden.setFechaIngreso(new Timestamp(System.currentTimeMillis()));
        orden.setKilometraje(kilometraje);
        orden.setSintomas(txtSintomas.getText());
        orden.setDiagnosticoPreliminar(txtDiagnostico.getText());
        orden.setResponsable(idMecanico);
        orden.setEstado(cbmEstado.getSelectedItem().toString());

        OrdenTrabajoDAO dao = new OrdenTrabajoDAO();

        if (dao.registrar(orden)) {

            JOptionPane.showMessageDialog(this,
                    "Orden de trabajo registrada correctamente.");

            limpiarCampos();

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar la orden.");
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Ingrese un kilometraje válido.");
    }

    }//GEN-LAST:event_btnGuardarActionPerformed

