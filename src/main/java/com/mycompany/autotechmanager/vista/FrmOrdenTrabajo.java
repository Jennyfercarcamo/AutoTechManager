    private void cargarClientes() {

    ClienteDAO dao = new ClienteDAO();
    ArrayList<Cliente> lista = dao.listar();

    cbmCliente.removeAllItems();

    for (Cliente cliente : lista) {
        cbmCliente.addItem(
                cliente.getIdCliente() + " - " + cliente.getNombre()
        );
    }
}
    private void cargarVehiculos() {

    cbmVehiculo.removeAllItems();

    if (cbmCliente.getSelectedItem() == null) {
        return;
    }

    String seleccionado = cbmCliente.getSelectedItem().toString();
    int idCliente = Integer.parseInt(seleccionado.split(" - ")[0]);

    VehiculoDAO dao = new VehiculoDAO();
    ArrayList<Vehiculo> lista = dao.listarPorCliente(idCliente);

    for (Vehiculo vehiculo : lista) {
        cbmVehiculo.addItem(
                vehiculo.getIdVehiculo() + " - "
                + vehiculo.getMarca() + " "
                + vehiculo.getModelo() + " - "
                + vehiculo.getPlaca()
        );
    }
}
    private void cargarMecanicos() {

    MecanicoDAO dao = new MecanicoDAO();
    ArrayList<Mecanico> lista = dao.listar();

    cbmMecanico.removeAllItems();

    for (Mecanico mecanico : lista) {
        cbmMecanico.addItem(
                mecanico.getIdMecanico() + " - "
                + mecanico.getNombre()
        );
    }
}
    
    private void cargarOrdenes() {

    OrdenTrabajoDAO dao = new OrdenTrabajoDAO();
    ArrayList<OrdenTrabajo> lista = dao.listar();

    DefaultTableModel modelo = (DefaultTableModel) tblOrdenes.getModel();
    modelo.setRowCount(0);

    for (OrdenTrabajo orden : lista) {

        modelo.addRow(new Object[]{
            orden.getIdOrden(),
            orden.getFechaIngreso(),
            orden.getIdCliente(),
            orden.getIdVehiculo(),
            orden.getResponsable(),
            orden.getEstado(),
            orden.getSintomas()
        });
    }
}
