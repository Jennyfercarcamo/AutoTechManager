    private void cargarImagenes() {

    java.net.URL rutaEncabezado = getClass().getResource(
           "/imagenes/AutoTechManager_Encabezado.png"
      );


    java.net.URL rutaLateral = getClass().getResource(
      "/imagenes/AutoTechManager_Lateral.png"
      );

    if (rutaEncabezado == null || rutaLateral == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No se encontraron las imágenes."
        );
        return;
    }

    javax.swing.ImageIcon imagenEncabezado =
        new javax.swing.ImageIcon(rutaEncabezado);

    javax.swing.ImageIcon imagenLateral =
        new javax.swing.ImageIcon(rutaLateral);

    lblEncabezado.setIcon(new javax.swing.ImageIcon(
        imagenEncabezado.getImage().getScaledInstance(
            lblEncabezado.getWidth(),
            lblEncabezado.getHeight(),
            java.awt.Image.SCALE_SMOOTH
        )
    ));

    lblLateral.setIcon(new javax.swing.ImageIcon(
        imagenLateral.getImage().getScaledInstance(
            lblLateral.getWidth(),
            lblLateral.getHeight(),
            java.awt.Image.SCALE_SMOOTH
        )
    ));

    lblEncabezado.setText("");
    lblLateral.setText("");
}
    
    private void cargarClientes() {

    ClienteDAO dao = new ClienteDAO();

    ArrayList<Cliente> lista = dao.listar();

    DefaultTableModel modelo =
            (DefaultTableModel) tblClientes.getModel();

    modelo.setRowCount(0);

    for (Cliente cliente : lista) {

        modelo.addRow(new Object[]{
            cliente.getIdCliente(),
            cliente.getNombre(),
            cliente.getDni(),
            cliente.getTelefono(),
            cliente.getCorreo(),
            cliente.getDireccion(),
            cliente.getEstado() ? "Activo" : "Inactivo"
        });
    }
}

