    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (txtNombre.getText().trim().isEmpty()
            || txtDNI.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Ingrese el nombre y DNI del cliente");

        return;
    }

    Cliente cliente = new Cliente();

    cliente.setNombre(txtNombre.getText());
    cliente.setDni(txtDNI.getText());
    cliente.setTelefono(txtTelefono.getText());
    cliente.setCorreo(txtCorreo.getText());
    cliente.setDireccion(txtDireccion.getText());
    cliente.setEstado(chkActivo.isSelected());

    ClienteDAO dao = new ClienteDAO();

    if (dao.registrar(cliente)) {

        JOptionPane.showMessageDialog(this,
                "Cliente registrado correctamente");
        cargarClientes();

        txtNombre.setText("");
        txtDNI.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        txtDireccion.setText("");
        chkActivo.setSelected(true);

    } else {

        JOptionPane.showMessageDialog(this,
                "Error al registrar el cliente");
    }

    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
        // TODO add your handling code here:
         int fila = tblClientes.getSelectedRow();

    if (fila >= 0) {
        txtIdCliente.setText(tblClientes.getValueAt(fila, 0).toString());
        txtNombre.setText(tblClientes.getValueAt(fila, 1).toString());
        txtDNI.setText(tblClientes.getValueAt(fila, 2).toString());
        txtTelefono.setText(tblClientes.getValueAt(fila, 3).toString());
        txtCorreo.setText(tblClientes.getValueAt(fila, 4).toString());
        txtDireccion.setText(tblClientes.getValueAt(fila, 5).toString());

        chkActivo.setSelected(
                tblClientes.getValueAt(fila, 6).toString().equals("Activo")
        );
    }

    }//GEN-LAST:event_tblClientesMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
          if (txtIdCliente.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un cliente de la tabla");
        return;
    }

    Cliente cliente = new Cliente();

    cliente.setIdCliente(Integer.parseInt(txtIdCliente.getText()));
    cliente.setNombre(txtNombre.getText());
    cliente.setDni(txtDNI.getText());
    cliente.setTelefono(txtTelefono.getText());
    cliente.setCorreo(txtCorreo.getText());
    cliente.setDireccion(txtDireccion.getText());
    cliente.setEstado(chkActivo.isSelected());

    ClienteDAO dao = new ClienteDAO();

    if (dao.actualizar(cliente)) {
        JOptionPane.showMessageDialog(this,
                "Cliente actualizado correctamente");

        cargarClientes();
    } else {
        JOptionPane.showMessageDialog(this,
                "Error al actualizar el cliente");
    }

    }//GEN-LAST:event_btnActualizarActionPerformed

