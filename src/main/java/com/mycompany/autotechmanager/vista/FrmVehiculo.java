    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblVehiculos.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this,
            "Selecciona un vehículo de la tabla.");
    return;
}

int idVehiculo = Integer.parseInt(
        tblVehiculos.getValueAt(fila, 0).toString());

int confirmar = JOptionPane.showConfirmDialog(this,
        "¿Seguro que deseas eliminar este vehículo?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION);

if (confirmar == JOptionPane.YES_OPTION) {

    VehiculoDAO dao = new VehiculoDAO();

    if (dao.eliminar(idVehiculo)) {

        JOptionPane.showMessageDialog(this,
                "Vehículo eliminado correctamente.");

        cargarVehiculos();

        txtPlaca.setText("");
        txtVIN.setText("");
        txtMarca.setText("");
        txtModelo.setText("");
        txtAnio.setText("");
        txtColor.setText("");
        txtKilometraje.setText("");

    } else {

        JOptionPane.showMessageDialog(this,
                "No se pudo eliminar el vehículo.");
    }
}
    }//GEN-LAST:event_btnEliminarActionPerformed

