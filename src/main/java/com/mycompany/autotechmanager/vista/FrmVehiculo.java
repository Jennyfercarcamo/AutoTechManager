   private void cargarClientes() {

    ClienteDAO daoCliente = new ClienteDAO();

    ArrayList<Cliente> lista = daoCliente.listar();

    cbmCliente.removeAllItems();

    for (Cliente cliente : lista) {
        cbmCliente.addItem(cliente.getNombre());
    }
    
   }
  
    private void cargarVehiculos() {

    VehiculoDAO daoVehiculo = new VehiculoDAO();
    ClienteDAO daoCliente = new ClienteDAO();

    ArrayList<Vehiculo> listaVehiculos = daoVehiculo.listar();
    ArrayList<Cliente> listaClientes = daoCliente.listar();

    DefaultTableModel modelo =
            (DefaultTableModel) tblVehiculos.getModel();

    modelo.setRowCount(0);

    for (Vehiculo vehiculo : listaVehiculos) {

        String nombreCliente = "";

        for (Cliente cliente : listaClientes) {

            if (cliente.getIdCliente() == vehiculo.getIdCliente()) {
                nombreCliente = cliente.getNombre();
                break;
            }
        }

        modelo.addRow(new Object[]{
            vehiculo.getIdVehiculo(),
            nombreCliente,
            vehiculo.getPlaca(),
            vehiculo.getVin(),
            vehiculo.getMarca(),
            vehiculo.getModelo(),
            vehiculo.getAnio(),
            vehiculo.getColor(),
            vehiculo.getKilometraje(),
            vehiculo.getCombustible()
        });
    }  
}   
    
    private void buscarPorPlaca() {

    DefaultTableModel modelo =
            (DefaultTableModel) tblVehiculos.getModel();

    javax.swing.table.TableRowSorter<DefaultTableModel> sorter =
            new javax.swing.table.TableRowSorter<>(modelo);

    tblVehiculos.setRowSorter(sorter);

    String texto = txtBuscar.getText().trim();

    if (texto.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(
                javax.swing.RowFilter.regexFilter(
                        "(?i)" + java.util.regex.Pattern.quote(texto), 2));
    }

}
   

