    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        try {

    int fila = tblVehiculos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecciona un vehículo de la tabla.");
        return;
    }

    Vehiculo vehiculo = new Vehiculo();

    // ID del vehículo seleccionado
    vehiculo.setIdVehiculo(
            Integer.parseInt(tblVehiculos.getValueAt(fila, 0).toString()));

    // Buscar ID del cliente
    String nombreCliente = cbmCliente.getSelectedItem().toString();

    ClienteDAO daoCliente = new ClienteDAO();

    for (Cliente cliente : daoCliente.listar()) {
        if (cliente.getNombre().equals(nombreCliente)) {
            vehiculo.setIdCliente(cliente.getIdCliente());
            break;
        }
    }

    vehiculo.setPlaca(txtPlaca.getText());
    vehiculo.setVin(txtVIN.getText());
    vehiculo.setMarca(txtMarca.getText());
    vehiculo.setModelo(txtModelo.getText());
    vehiculo.setAnio(Integer.parseInt(txtAnio.getText()));
    vehiculo.setColor(txtColor.getText());
    vehiculo.setKilometraje(Integer.parseInt(txtKilometraje.getText()));
    vehiculo.setCombustible(cbmCombustible.getSelectedItem().toString());

    VehiculoDAO dao = new VehiculoDAO();

    if (dao.actualizar(vehiculo)) {

        JOptionPane.showMessageDialog(this,
                "Vehículo actualizado correctamente.");

        cargarVehiculos();

    } else {

        JOptionPane.showMessageDialog(this,
                "No se pudo actualizar el vehículo.");
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Verifica que el año y kilometraje sean números.");

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}
        
    }//GEN-LAST:event_btnActualizarActionPerformed

