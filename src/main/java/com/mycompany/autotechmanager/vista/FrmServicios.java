    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        

    int fila = tblServicios.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un servicio de la tabla.");
        return;
    }

    try {

        Servicio servicio = new Servicio();

        servicio.setIdServicio(
                Integer.parseInt(tblServicios.getValueAt(fila, 0).toString()));

        servicio.setCodigo(txtCodigo.getText().trim());
        servicio.setNombre(txtNombre.getText().trim());
        servicio.setDescripcion(txtDescripcion.getText().trim());
        servicio.setNivelComplejidad(
                Integer.parseInt(cbmNivel.getSelectedItem().toString()));
        servicio.setCostoManoObra(
                Double.parseDouble(txtCosto.getText().trim()));
        servicio.setTiempoEstimado(
                Double.parseDouble(txtTiempo.getText().trim()));

        ServicioDAO dao = new ServicioDAO();

        if (dao.actualizar(servicio, chkActivo.isSelected())) {

            JOptionPane.showMessageDialog(this,
                    "Servicio actualizado correctamente.");

            cargarTabla();
            limpiar();

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo actualizar el servicio.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Revise los campos numéricos.");
    }
          
    }//GEN-LAST:event_btnActualizarActionPerformed

