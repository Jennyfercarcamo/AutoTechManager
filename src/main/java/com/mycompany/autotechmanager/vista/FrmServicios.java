    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
    try {

        if (txtCodigo.getText().trim().isEmpty()
                || txtNombre.getText().trim().isEmpty()
                || txtCosto.getText().trim().isEmpty()
                || txtTiempo.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(null,
                    "Complete los campos obligatorios.");
            return;
        }

        Servicio servicio = new Servicio();

        servicio.setCodigo(txtCodigo.getText().trim());
        servicio.setNombre(txtNombre.getText().trim());
        servicio.setDescripcion(txtDescripcion.getText().trim());

        servicio.setNivelComplejidad(
                Integer.parseInt(cbmNivel.getSelectedItem().toString()));

        servicio.setCostoManoObra(
                Double.parseDouble(txtCosto.getText().trim()));

        servicio.setTiempoEstimado(
                Double.parseDouble(txtTiempo.getText().trim()));

        ServicioDAO dao = new ServicioDAO();

        if (dao.registrar(servicio)) {

            JOptionPane.showMessageDialog(null,
                    "Servicio registrado correctamente.");
            
             cargarTabla();
             limpiar();


        } else {

            JOptionPane.showMessageDialog(null,
                    "No se pudo registrar el servicio.");
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(null,
                "Ingrese valores numéricos válidos.");

    } catch (Exception e) {

        JOptionPane.showMessageDialog(null,
                "Error: " + e.getMessage());
    }

    

    }//GEN-LAST:event_btnGuardarActionPerformed

