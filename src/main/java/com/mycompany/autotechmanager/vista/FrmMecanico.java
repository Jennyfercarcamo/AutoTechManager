    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
          if (txtNombre.getText().trim().isEmpty()
            || txtDNI.getText().trim().isEmpty()
            || txtTelefono.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Complete los campos obligatorios.");
        return;
    }

    Mecanico mecanico = new Mecanico();

    mecanico.setNombre(txtNombre.getText().trim());
    mecanico.setDni(txtDNI.getText().trim());
    mecanico.setTelefono(txtTelefono.getText().trim());
    mecanico.setEspecialidad(cbmEspecialidad.getSelectedItem().toString());
    mecanico.setEstado(chkActivo.isSelected());

    MecanicoDAO dao = new MecanicoDAO();

    if (dao.registrar(mecanico)) {
        JOptionPane.showMessageDialog(this,
                "Mecánico registrado correctamente.");

        cargarTabla();
        limpiar();
    } else {
        JOptionPane.showMessageDialog(this,
                "Error al registrar mecánico.");
    }

        
    }//GEN-LAST:event_btnGuardarActionPerformed

