    private void tblMecanicosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMecanicosMouseClicked
        // TODO add your handling code here:
         int fila = tblMecanicos.getSelectedRow();

    if (fila >= 0) {
        txtNombre.setText(tblMecanicos.getValueAt(fila, 1).toString());
        txtDNI.setText(tblMecanicos.getValueAt(fila, 2).toString());
        txtTelefono.setText(tblMecanicos.getValueAt(fila, 3).toString());

        cbmEspecialidad.setSelectedItem(
                tblMecanicos.getValueAt(fila, 4).toString()
        );

        chkActivo.setSelected(
                tblMecanicos.getValueAt(fila, 5).toString().equals("Activo")
        );
    }

        
    }//GEN-LAST:event_tblMecanicosMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
         int fila = tblMecanicos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un mecánico de la tabla.");
        return;
    }

    Mecanico mecanico = new Mecanico();

    mecanico.setIdMecanico(
            Integer.parseInt(tblMecanicos.getValueAt(fila, 0).toString()));

    mecanico.setNombre(txtNombre.getText().trim());
    mecanico.setDni(txtDNI.getText().trim());
    mecanico.setTelefono(txtTelefono.getText().trim());
    mecanico.setEspecialidad(
            cbmEspecialidad.getSelectedItem().toString());
    mecanico.setEstado(chkActivo.isSelected());

    MecanicoDAO dao = new MecanicoDAO();

    if (dao.actualizar(mecanico)) {
        JOptionPane.showMessageDialog(this,
                "Mecánico actualizado correctamente.");

        cargarTabla();
        limpiar();
    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo actualizar el mecánico.");
    }

    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarActionPerformed
        // TODO add your handling code here:
         int fila = tblMecanicos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un mecánico de la tabla.");
        return;
    }

    int idMecanico = Integer.parseInt(
            tblMecanicos.getValueAt(fila, 0).toString());

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea desactivar este mecánico?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION);

    if (respuesta == JOptionPane.YES_OPTION) {
        MecanicoDAO dao = new MecanicoDAO();

        if (dao.desactivar(idMecanico)) {
            JOptionPane.showMessageDialog(this,
                    "Mecánico desactivado correctamente.");

            cargarTabla();
            limpiar();
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo desactivar el mecánico.");
        }
    }

        
    }//GEN-LAST:event_btnDesactivarActionPerformed

